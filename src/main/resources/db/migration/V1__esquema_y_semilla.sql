CREATE TABLE cliente (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento VARCHAR2(11) NOT NULL UNIQUE,
  nombres VARCHAR2(120) NOT NULL,
  telefono VARCHAR2(15)
);
CREATE TABLE servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(7) NOT NULL UNIQUE,
  nombre VARCHAR2(80) NOT NULL,
  precio NUMBER(10,2) NOT NULL CHECK (precio > 0),
  duracion_min NUMBER(4) NOT NULL CHECK (duracion_min BETWEEN 15 AND 480),
  activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);
CREATE TABLE vehiculo (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR2(7) NOT NULL UNIQUE,
  marca VARCHAR2(40) NOT NULL,
  modelo VARCHAR2(40) NOT NULL,
  anio NUMBER(4) NOT NULL CHECK (anio BETWEEN 1990 AND 2027),
  cliente_id NUMBER NOT NULL REFERENCES cliente(id)
);
CREATE SEQUENCE seq_numero_orden START WITH 5 INCREMENT BY 1 NOCACHE;
CREATE TABLE orden_servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(9) NOT NULL UNIQUE,
  fecha TIMESTAMP NOT NULL,
  vehiculo_id NUMBER NOT NULL REFERENCES vehiculo(id),
  kilometraje NUMBER(7) NOT NULL,
  estado VARCHAR2(12) NOT NULL CHECK (estado IN ('REGISTRADA', 'ANULADA')),
  total NUMBER(10,2) NOT NULL CHECK (total >= 0),
  usuario_registro VARCHAR2(30) NOT NULL,
  motivo_anulacion VARCHAR2(200)
);
CREATE TABLE detalle_orden (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER NOT NULL REFERENCES orden_servicio(id),
  servicio_id NUMBER NOT NULL REFERENCES servicio(id),
  cantidad NUMBER(2) NOT NULL CHECK (cantidad BETWEEN 1 AND 5),
  precio_unitario NUMBER(10,2) NOT NULL CHECK (precio_unitario > 0),
  subtotal NUMBER(10,2) NOT NULL CHECK (subtotal > 0),
  CONSTRAINT uq_detalle_orden_servicio UNIQUE (orden_id, servicio_id)
);
CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(30) NOT NULL UNIQUE,
  password VARCHAR2(100) NOT NULL,
  nombrecompleto VARCHAR2(120) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(30) NOT NULL UNIQUE
);
CREATE TABLE usuario_roles (
  usuarioid NUMBER NOT NULL REFERENCES usuarios(id),
  rolid NUMBER NOT NULL REFERENCES roles(id),
  CONSTRAINT pk_usuario_roles PRIMARY KEY (usuarioid, rolid)
);
CREATE INDEX ix_vehiculo_cliente ON vehiculo(cliente_id);
CREATE INDEX ix_orden_vehiculo_fecha ON orden_servicio(vehiculo_id, fecha DESC);
CREATE INDEX ix_orden_estado_fecha ON orden_servicio(estado, fecha DESC);
CREATE INDEX ix_detalle_servicio ON detalle_orden(servicio_id);
